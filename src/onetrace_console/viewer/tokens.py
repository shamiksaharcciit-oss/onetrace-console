"""The onetrace Console Skin's design tokens, read from the vendored skin — never retyped.

The viewer's token source is the **onetrace Console Skin v1**, the sealed
token block issued from the v6 release boards, in place of the oneview spec (whose dark
single theme the boards replaced for onetrace's console and viewer). `_vendor/` holds the sealed
ruling itself, byte for byte; §3 is the block. onedoor's and onewatch's copies of the oneview spec
are untouched, and this module still does **not** import `canary.viewer.tokens`: by design
(022 §2) nothing in `viewer/` imports from `canary/`, so that this package can leave for
the SDK repository with one `git mv` and no untangling.

The two pins below -- the whole file's sha256, as 10-01ck §1 asks, and §3's block's -- were
computed from the vendored bytes by tooling and written in by script (X-11).

X-6: the spec is a hard requirement. A missing or drifted spec **raises**; there is no
bundled palette to fall back to.

This is the only module in `viewer/` besides `fingerprint.py` that imports `hashlib`, and
it hashes the vendored spec, never a record. `viewer/tests/test_structure.py` asserts both.
"""
from __future__ import annotations

import hashlib
import re
from functools import lru_cache
from pathlib import Path

SPEC_PATH = Path(__file__).parent / "_vendor" / "ONETRACE_CONSOLE_SKIN_v1.md"

SPEC_DIGEST = "6386e640be5a9f47111b6a54cd55bad8afe504c803fb995562837da3844a517b"
"""sha256 of the whole vendored spec file. Generated by tooling, never typed."""

SPEC_FENCE_DIGEST = "734a1ebf8466c9e107784fcd526ead604b5294f07a39c9026d03f46508733422"
"""sha256 of the spec's §4 CSS fence contents. Generated by tooling, never typed."""

_FENCE = re.compile(r"```css\n(.*?)```", re.S)
_DECL = re.compile(r"(--[a-z-]+)\s*:\s*(#[0-9A-Fa-f]{6})")


class TokenError(RuntimeError):
    """The spec could not be read, or does not carry what was vendored from it."""


@lru_cache(maxsize=1)
def css_block() -> str:
    """The skin's §3 fence, verbatim, with both pins checked before it is used."""
    if not SPEC_PATH.is_file():
        raise TokenError(
            f"the Console Skin is not where the viewer expects it: {SPEC_PATH}. "
            f"The design system is a hard requirement (X-6); there is no bundled palette.")
    raw = SPEC_PATH.read_bytes()
    if hashlib.sha256(raw).hexdigest() != SPEC_DIGEST:
        raise TokenError("the vendored spec's bytes have changed. Re-vendor deliberately; "
                         "do not absorb a design change without looking at it.")
    match = _FENCE.search(raw.decode("utf-8"))
    if match is None:
        raise TokenError("the design spec has no ```css fence; §4 is the token authority")
    block = match.group(1)
    if hashlib.sha256(block.encode("utf-8")).hexdigest() != SPEC_FENCE_DIGEST:
        raise TokenError("the spec's token block has changed. Re-vendor deliberately.")
    return block


@lru_cache(maxsize=1)
def palette() -> dict[str, str]:
    """`{token name: #rrggbb}` parsed from the vendored block."""
    return {name: value.lower() for name, value in _DECL.findall(css_block())}


def root_css() -> str:
    """The `:root` rule for an emitted page: the skin's §3 block, verbatim.

    The block carries the font stacks itself ('IBM Plex Sans' and 'IBM Plex Mono', each falling
    back to system fonts). Nothing is fetched here: the free viewer file shows the system fonts,
    and the console serves IBM Plex from its own package.
    """
    return css_block().rstrip("\n")

# ------------------------------------------------------------------ the dark theme

DARK_PATH = Path(__file__).parent / "_vendor" / "TOKENS_DARK.css"

DARK_DIGEST = "71ff312a749f7541d007482dd49f2aee0b7cb06416809defb66a8e2fe32e6f1b"
"""sha256 of the vendored dark tokens: the visual target's own file, its closing comment removed
(it named a ruling by its id) and its tokens unchanged. Generated by tooling."""

DERIVED_PATH = Path(__file__).parent / "dark_derived.css"

_DARK_DECL = re.compile(r"(--[a-z0-9-]+)\s*:\s*(#[0-9A-Fa-f]{6}|rgba\([^)]*\))")

#: Each skin role in the dark theme: a token of the target's file, or ("blend", a translucent
#: token, the opaque token it is drawn over), mixed here into the colour a reader sees, so the
#: contrast test reads real colours. Three roles the target's file has no token for are derived
#: and say so: the accent (links, focus, the declined outline), its ink, and the navigation.
DARK_ROLES: dict[str, object] = {
    "page": "--bg", "surface": ("blend", "--surface", "--bg"), "surface-sunk": "--bg",
    "surface-alt": "--node",
    "ink": "--text", "ink-soft": "--neutral-text", "ink-muted": "--text-muted",
    "ink-faint": "--text-faint",
    "line": ("blend", "--border", "--node"), "line-soft": ("blend", "--border", "--bg"),
    "line-node": ("blend", "--border-strong", "--node"), "line-strong": "--text-faint",
    "accent": ("derived", "--accent"), "accent-ink": "--bg",
    "nav-bg": "--bg", "nav-ink": "--neutral-text", "nav-ink-faint": "--text-faint",
    "nav-on-bg": "--bg-glow-1", "nav-on-ink": "--text-strong",
    "ok-bg": ("blend", "--same-bg", "--node"), "ok-ink": "--same-text",
    "cc-bg": ("blend", "--amber-bg", "--node"), "cc-ink": "--amber-text", "hl": "--glow-bg",
    "bad-bg": ("blend", "--bad-bg", "--node"), "bad-ink": "--bad-text",
    "neu-bg": ("blend", "--neutral-bg", "--node"), "neu-ink": "--neutral-text",
}
#: The roles above whose dark value is not a token of the target's file, each with why.
DARK_DERIVED = {
    "accent": "the target names a blue outline for a declined run but gives no blue; this one "
              "reads at 4.5:1 or more on every dark ground",
    "accent-ink": "text on the accent: the page's own ground",
    "nav-bg": "the target draws no navigation; the page's ground, the panel set off by its line",
}


@lru_cache(maxsize=1)
def dark_source() -> dict[str, str]:
    """{token: value} from the vendored dark tokens, its pin checked first (X-6: it raises)."""
    if not DARK_PATH.is_file():
        raise TokenError(f"the dark tokens are not where the viewer expects them: {DARK_PATH}")
    raw = DARK_PATH.read_bytes()
    if hashlib.sha256(raw).hexdigest() != DARK_DIGEST:
        raise TokenError("the vendored dark tokens' bytes have changed. Re-vendor deliberately.")
    return dict(_DARK_DECL.findall(raw.decode("utf-8")))


def _rgb(value: str) -> tuple[tuple[int, int, int], float]:
    if value.startswith("#"):
        return tuple(int(value[i:i + 2], 16) for i in (1, 3, 5)), 1.0
    parts = [p.strip() for p in value[value.index("(") + 1:-1].split(",")]
    return tuple(int(p) for p in parts[:3]), float(parts[3]) if len(parts) > 3 else 1.0


def _dark(role: str) -> str:
    source = dark_source()
    how = DARK_ROLES[role]
    if isinstance(how, tuple) and how[0] == "derived":
        return dict(_DARK_DECL.findall(DERIVED_PATH.read_text(encoding="utf-8")))[how[1]].lower()
    if isinstance(how, str):
        return source[how].lower()
    _, over, under = how
    (fr, fg, fb), alpha = _rgb(source[over])
    (ur, ug, ub), _ = _rgb(_dark_base(under))
    mix = (round(alpha * f + (1 - alpha) * u) for f, u in ((fr, ur), (fg, ug), (fb, ub)))
    return "#" + "".join(f"{c:02x}" for c in mix)


def _dark_base(token: str) -> str:
    """An opaque token of the target's file, the ground a translucent one is drawn over."""
    value = dark_source()[token]
    if not value.startswith("#"):
        raise TokenError(f"{token} is not opaque, so nothing can be drawn over it")
    return value


@lru_cache(maxsize=1)
def dark_palette() -> dict[str, str]:
    """{skin role: #rrggbb} in the dark theme, every role the light skin has."""
    missing = set(palette_names()) - set(DARK_ROLES)
    if missing:
        raise TokenError(f"the dark theme gives no value for {sorted(missing)}")
    return {role: _dark(role) for role in DARK_ROLES}


def palette_names() -> list[str]:
    return [name[2:] for name in palette()]


def theme_css() -> str:
    """The dark theme: the same roles, darker, when the reader's system asks for dark and the
    page is not set to light, or when the page is set to dark. The light skin stays the
    default; nothing else in any stylesheet changes, as every colour is a role."""
    decls = "".join(f"--{r}:{v};" for r, v in dark_palette().items())
    return (":root{color-scheme:light}\n"
            f"@media (prefers-color-scheme:dark){{:root:not([data-theme=light]){{color-scheme:dark;{decls}}}}}\n"
            f":root[data-theme=dark]{{color-scheme:dark;{decls}}}")


# ------------------------------------------------------------------ the type scale and corners

#: The skin's size and corner roles, set from the visual target's own tokens in both themes:
#: (skin role, the target's token). The figures' size (`--fs-kpi`) has no token in the target and
#: keeps the skin's.
SCALE_ROLES = (("fs-small", "--fs-small"), ("fs-body", "--fs-body"), ("fs-h1", "--fs-h1"),
               ("fs-nav", "--fs-eyebrow"), ("r-card", "--radius-card"), ("r-pill", "--radius-chip"))
_SIZE_DECL = re.compile(r"(--[a-z0-9-]+)\s*:\s*(\d+px)")


@lru_cache(maxsize=1)
def scale() -> dict[str, str]:
    """{skin role: px} from the vendored target tokens (its pin checked first)."""
    dark_source()
    sizes = dict(_SIZE_DECL.findall(DARK_PATH.read_text(encoding="utf-8")))
    missing = [t for _, t in SCALE_ROLES if t not in sizes]
    if missing:
        raise TokenError(f"the target's tokens give no size for {missing}")
    return {role: sizes[token] for role, token in SCALE_ROLES}


def scale_css() -> str:
    """The target's type scale and corners, one rule for both themes, after the skin's block."""
    return ":root{" + "".join(f"--{r}:{v};" for r, v in scale().items()) + "}"
